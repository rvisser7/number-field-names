"""Multiquadratic fields Q(\\sqrt{d_1}, ..., \\sqrt{d_k}), of degree 2^k with k >= 2.

Such a field K is determined by the group V of d in Q^*/Q^{*2} with \\sqrt{d} in K, an
F_2-vector space of rank k; its 2^k - 1 nontrivial elements, as squarefree integers, give
the quadratic subfields Q(\\sqrt{d}). As in the LMFDB's field_pretty, K is named by the
greedy basis of V: go through the d in V ordered by |d| (positive first on a tie) and keep
each one not in the span of those kept so far. Writing \\sqrt{-1} as i, this gives e.g.
\\Q(i, \\sqrt{2}) and \\Q(\\sqrt{2}, \\sqrt{3}, \\sqrt{5}).

We run over the V whose greedy basis has every |d_i| <= bound.
"""

from math import prod

from nf_names import is_squarefree


def order_key(d):
    return (abs(d), -d)


def sqrt_symbol(d):
    return "i" if d == -1 else r"\sqrt{%d}" % d


def multiquadratic_name(basis):
    return r"\Q(%s)" % ", ".join(sqrt_symbol(d) for d in basis)


def span(basis):
    """The squarefree d != 1 in the group generated by basis (mod squares)."""
    out = [1]
    for b in basis:
        out += [squarefree_part(a * b) for a in out]
    return out[1:]


def squarefree_part(n):
    sign, n = (-1 if n < 0 else 1), abs(n)
    out, p = 1, 2
    while p * p <= n:
        while n % (p * p) == 0:
            n //= p * p
        if n % p == 0:
            out *= p
            n //= p
        p += 1
    return sign * out * n


def quadratic_disc(d):
    return d if d % 4 == 1 else 4 * d


def disc_and_r1(basis):
    """Discriminant and number of real places of Q(\\sqrt{d} : d in basis).

    By the conductor-discriminant formula, |disc| is the product of the |disc| of the
    quadratic subfields. K is totally real if every d > 0, and totally complex otherwise.
    """
    ds = span(basis)
    n = 2 ** len(basis)
    r1 = n if all(d > 0 for d in ds) else 0
    r2 = (n - r1) // 2
    return (-1) ** r2 * prod(abs(quadratic_disc(d)) for d in ds), r1


def greedy_bases(rank, bound):
    """All greedy bases (see above) of rank `rank` with every |d_i| <= bound, in order."""
    cands = sorted((d for d in range(-bound, bound + 1) if d not in (0, 1) and is_squarefree(d)),
                   key=order_key)

    def extend(basis, spanned, start):
        if len(basis) == rank:
            yield tuple(basis)
            return
        for j in range(start, len(cands)):
            d = cands[j]
            if d in spanned:
                continue
            # d must be the first element of V outside the span of basis, so the
            # whole coset d * span(basis) must come after d.
            coset = [squarefree_part(d * a) for a in spanned]
            if any(order_key(c) < order_key(d) for c in coset):
                continue
            yield from extend(basis + [d], spanned | {d} | set(coset), j + 1)

    yield from extend([], set(), 0)


def multiquadratic_coeffs(basis):
    """polredabs polynomial (constant term first) of Q(\\sqrt{d} : d in basis)."""
    from pari_fields import pari, polredabs_coeffs
    f = pari(f"x^2 - ({basis[0]})")
    for d in basis[1:]:
        # polredbest keeps the coefficients small on the way up; polredabs is done once at the end
        f = pari.polredbest(pari.polcompositum(f, pari(f"x^2 - ({d})"))[0])
    return polredabs_coeffs(f)
